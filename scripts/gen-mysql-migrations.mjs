/**
 * Generates server/src/db/mysqlMigrations.ts from pgMigrations.ts.
 * Run: npx tsx scripts/gen-mysql-migrations.mjs
 *
 * Transformations:
 *  - IDENTITY PKs -> BIGINT AUTO_INCREMENT
 *  - TEXT columns that appear in UNIQUE/INDEX/PK -> VARCHAR(191) (MySQL
 *    requires a key length for string keys)
 *  - FK columns INTEGER -> BIGINT (must match the referenced PK type)
 *  - partial/function indexes -> plain column indexes (no WHERE/lower())
 *  - table options ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
 *  - statements are split so migrate can skip ones that already exist
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pgMigrations } from '../server/src/db/pgMigrations.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(here, '..', 'server', 'src', 'db', 'mysqlMigrations.ts');

// Global marks: indexes in later migrations reference columns defined by
// earlier migrations' CREATE TABLE statements, so collection spans all of them.
const indexed = new Map(); // table -> Set(column)
const fkInt = new Map(); // table -> Set(column)

const mark = (tbl, col) => {
  if (!indexed.has(tbl)) indexed.set(tbl, new Set());
  indexed.get(tbl).add(col.toLowerCase());
};

/** Normalizes CREATE INDEX: strips IF NOT EXISTS, lower(), and partial WHERE. */
function rewriteIndexes(s) {
  let out = s.replace(/(CREATE\s+(?:UNIQUE\s+)?INDEX)\s+IF\s+NOT\s+EXISTS/gi, '$1');
  const parts = [];
  let pos = 0;
  const re = /CREATE\s+(UNIQUE\s+)?INDEX\s+(\w+)\s+ON\s+(\w+)\s*\(/gi;
  let m;
  while ((m = re.exec(out))) {
    parts.push(out.slice(pos, m.index));
    let depth = 1;
    let j = re.lastIndex;
    while (j < out.length && depth > 0) {
      if (out[j] === '(') depth++;
      else if (out[j] === ')') depth--;
      j++;
    }
    const inner = out.slice(re.lastIndex, j - 1).replace(/lower\((\w+)\)/gi, '$1');
    const semi = out.indexOf(';', j);
    const end = semi === -1 ? out.length : semi + 1;
    parts.push(`CREATE ${m[1] ?? ''}INDEX ${m[2]} ON ${m[3]}(${inner});`);
    pos = end;
    re.lastIndex = end;
  }
  parts.push(out.slice(pos));
  out = parts.join('');
  // Also normalize the trailing-semicolon statement (no WHERE left to strip).
  return out;
}

/** Fills the global mark maps from every migration's SQL. */
function collectMarks() {
  const all = rewriteIndexes(pgMigrations.map((m) => m.sql).join('\n'));

  for (const m of all.matchAll(/CREATE\s+(?:UNIQUE\s+)?INDEX\s+\w+\s+ON\s+(\w+)\s*\(([^)]*)\)\s*;/gi)) {
    const tbl = m[1];
    for (const part of m[2].split(',')) {
      const col = part.trim();
      if (!/^[A-Za-z_]\w*$/.test(col)) throw new Error(`Unsupported index expression: ${part} on ${tbl}`);
      mark(tbl, col);
    }
  }

  for (const m of all.matchAll(/CREATE TABLE (\w+) \(([\s\S]*?)\n\);/g)) {
    const tbl = m[1];
    const body = m[2];
    for (const c of body.matchAll(/^\s*([A-Za-z_]\w*)\s+[^\n]*\bUNIQUE\b/gmi)) mark(tbl, c[1]);
    for (const c of body.matchAll(/^\s*([A-Za-z_]\w*)\s+[^\n]*\bPRIMARY KEY\b/gmi)) mark(tbl, c[1]);
    for (const c of body.matchAll(/(?:PRIMARY KEY|UNIQUE(?:\s+\w+)?)\s*\(([^)]+)\)/gi)) {
      for (const p of c[1].split(',')) {
        const col = p.trim();
        if (/^[A-Za-z_]\w*$/.test(col)) mark(tbl, col);
      }
    }
    const fks = new Set();
    for (const c of body.matchAll(/^\s*([A-Za-z_]\w*)\s+INTEGER\b[^\n]*\bREFERENCES\b/gmi)) fks.add(c[1]);
    for (const c of body.matchAll(/FOREIGN KEY\s*\(([^)]+)\)/gi)) {
      for (const p of c[1].split(',')) fks.add(p.trim());
    }
    if (fks.size) fkInt.set(tbl, fks);
  }
}

function transform(sql) {
  let s = sql;

  // Identity columns.
  s = s.replace(
    /INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g,
    'BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY',
  );

  // Normalize CREATE INDEX statements (balance-aware — index expressions may
  // nest parentheses).
  s = rewriteIndexes(s);

  // Per-table column typing.
  s = s.replace(/CREATE TABLE (\w+) \(([\s\S]*?)\n\);/g, (whole, tbl, body) => {
    let b = body;
    for (const col of indexed.get(tbl) ?? []) {
      b = b.replace(new RegExp(`(\\b${col}\\s+)TEXT\\b`, 'i'), '$1VARCHAR(191)');
    }
    for (const col of fkInt.get(tbl) ?? []) {
      b = b.replace(new RegExp(`(\\b${col}\\s+)INTEGER\\b`, 'i'), '$1BIGINT');
    }
    return `CREATE TABLE ${tbl} (\n${b}\n);`;
  });

  // Columns added later via ALTER TABLE need the same TEXT -> VARCHAR(191)
  // upgrade when they participate in an index (MySQL needs a key length).
  for (const [tbl, cols] of indexed) {
    for (const col of cols) {
      s = s.replace(
        new RegExp(`(ALTER\\s+TABLE\\s+${tbl}\\s+ADD\\s+COLUMN\\s+${col}\\s+)TEXT\\b`, 'i'),
        '$1VARCHAR(191)',
      );
    }
  }

  // Remaining type rewrites.
  s = s.replace(/\bREAL\b/g, 'DOUBLE');
  s = s.replace(/\bNUMERIC\s*\(/gi, 'DECIMAL(');
  s = s.replace(/\bBOOLEAN\b/g, 'TINYINT(1)');
  // FK-typed columns must match the referenced BIGINT PK — applies to
  // ALTER TABLE ... ADD COLUMN ... REFERENCES as well as CREATE TABLE bodies.
  s = s.replace(/\bINTEGER\b(?=[^\n]*\bREFERENCES\b)/g, 'BIGINT');

  // Table options (every CREATE TABLE ends with a line containing ');').
  s = s.replace(/^(\s*)\);$/gm, '$1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;');

  // MySQL forbids plain defaults on TEXT columns; parenthesized expression
  // defaults (8.0.13+) are allowed — wrap literal defaults on TEXT columns
  // (column lines in CREATE TABLE and ALTER TABLE ... ADD COLUMN alike).
  s = s.replace(
    /([A-Za-z_]\w*[ \t]+TEXT\b[^,\n]*?\bDEFAULT[ \t]+)'([^']*)'/g,
    (_m, head, val) => `${head}('${val}')`,
  );

  // Split into idempotent statements (comment/string/paren aware — comments
  // may contain semicolons, e.g. "-- telephony webhooks; provider_call_id...").
  const statements = [];
  {
    let cur = '';
    let i = 0;
    const push = () => {
      const s = cur.trim();
      cur = '';
      const code = s.replace(/^\s*(--[^\n]*\n?|\/\*[\s\S]*?\*\/|\s)+/i, '');
      if (/^(CREATE|ALTER|DROP|INSERT|UPDATE|DELETE)\b/i.test(code)) statements.push(s);
    };
    while (i < s.length) {
      const c = s[i];
      if (c === "'" || c === '"') {
        const q = c;
        cur += c;
        i++;
        while (i < s.length) {
          cur += s[i];
          if (s[i] === '\\') {
            i++;
            if (i < s.length) {
              cur += s[i];
              i++;
            }
            continue;
          }
          if (s[i] === q) {
            i++;
            break;
          }
          i++;
        }
        continue;
      }
      if (c === '-' && s[i + 1] === '-') {
        while (i < s.length && s[i] !== '\n') {
          cur += s[i];
          i++;
        }
        continue;
      }
      if (c === '/' && s[i + 1] === '*') {
        while (i < s.length && !(s[i] === '*' && s[i + 1] === '/')) {
          cur += s[i];
          i++;
        }
        if (i < s.length) {
          cur += '*/';
          i += 2;
        }
        continue;
      }
      if (c === ';') {
        push();
        i++;
        continue;
      }
      cur += c;
      i++;
    }
    push();
  }

  // Sanity: nothing SQLite/PG-specific may survive.
  const bad =
    /GENERATED BY DEFAULT|AS IDENTITY|::|\bILIKE\b|\bRETURNING\b|COLLATE NOCASE|CONCURRENTLY|\bjsonb\b|\b(TEXT|INTEGER|INT|BIGINT|VARCHAR|DOUBLE|BOOLEAN)\s*\[\]/;
  for (const st of statements) {
    const m = st.match(bad);
    if (m) throw new Error(`Leftover ${m[0]} in statement: ${st.slice(0, 160)}`);
  }
  return statements;
}

const out = [
  '/**',
  ' * MySQL 8 port of the PostgreSQL migrations in pgMigrations.ts (same ids so',
  ' * schema_migrations stays in sync). Generated by scripts/gen-mysql-migrations.mjs',
  ' * — regenerate when pgMigrations.ts changes.',
  ' */',
  '',
  'export interface MysqlMigration {',
  '  id: string;',
  '  name: string;',
  '  /** Individual DDL statements; migrate() skips ones that already exist (MySQL',
  '   * DDL commits implicitly, so each statement is applied independently). */',
  '  statements: string[];',
  '}',
  '',
  'export const mysqlMigrations: MysqlMigration[] = [',
];

collectMarks();

for (const m of pgMigrations) {
  const statements = transform(m.sql);
  out.push('  {');
  out.push(`    id: ${JSON.stringify(m.id)},`);
  out.push(`    name: ${JSON.stringify(m.name)},`);
  out.push('    statements: [');
  for (const st of statements) out.push(`      ${JSON.stringify(st)},`);
  out.push('    ],');
  out.push('  },');
}
out.push('];');
out.push('');

fs.writeFileSync(outPath, out.join('\n'));
console.log(`wrote ${outPath}: ${pgMigrations.length} migrations`);
